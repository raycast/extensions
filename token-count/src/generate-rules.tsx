import {
  Detail,
  ActionPanel,
  Action,
  CopyToClipboardAction,
  showToast,
  Toast,
} from "@raycast/api";

interface RuleSnippet {
  pattern: string;
  rule: string;
}

/**
 * Extract Cursor Rules rule snippets from code
 */
function extractRules(code: string): RuleSnippet[] {
  const rules: RuleSnippet[] = [];

  // Extract naming conventions
  const namingConventions: { pattern: RegExp; name: string }[] = [
    { pattern: /[A-Z][a-zA-Z0-9]*[A-Z][a-zA-Z0-9]*/g, name: "CamelCase" },
    { pattern: /^[a-z][a-z0-9_]*$/gm, name: "snake_case" },
    { pattern: /^[A-Z][A-Z0-9_]+$/g, name: "SCREAMING_SNAKE" },
  ];

  for (const { pattern, name } of namingConventions) {
    const matches = code.match(pattern);
    if (matches && matches.length > 3) {
      rules.push({
        pattern: `Naming: ${name}`,
        rule: `// Use ${name} for identifiers in this codebase`,
      });
    }
  }

  // Extract import order preference
  const importOrder = code.match(/^import .+$/gm);
  if (importOrder && importOrder.length > 2) {
    rules.push({
      pattern: "Import Order",
      rule: `// Group imports: 1) React/Framework 2) Third-party 3) Internal\n${importOrder.slice(0, 3).join("\n")}`,
    });
  }

  // Extract comment style
  const jsdocComments = code.match(/\/\*\*[\s\S]*?\*\//g);
  if (jsdocComments && jsdocComments.length > 2) {
    rules.push({
      pattern: "Documentation",
      rule: `// Use JSDoc comments for all public functions
${jsdocComments[0].split("\n")[0]}`,
    });
  }

  // Extract common function patterns
  const functionPatterns = code.match(/(?:async\s+)?function\s+(\w+)|const\s+(\w+)\s*=\s*(?:async\s+)?(?:\([^)]*\)|[^=])/g);
  if (functionPatterns) {
    const uniqueNames = [...new Set(functionPatterns.map(f => f.split(/\s+/).pop()))];
    if (uniqueNames.length > 5) {
      rules.push({
        pattern: "Function Patterns",
        rule: `// Common functions: ${uniqueNames.slice(0, 5).join(", ")}`,
      });
    }
  }

  // Extract error handling patterns
  const tryCatchBlocks = code.match(/try\s*\{[\s\S]*?\}\s*catch/gi);
  if (tryCatchBlocks && tryCatchBlocks.length > 0) {
    rules.push({
      pattern: "Error Handling",
      rule: `// Always wrap async operations in try-catch blocks`,
    });
  }

  // Extract TypeScript type usage
  const typeUsages = code.match(/: ([A-Z]\w*(?:<[^>]+>)?)(?:\s*[=;])/g);
  if (typeUsages && typeUsages.length > 3) {
    const types = [...new Set(typeUsages.map(t => t.replace(/:\s*/, "")))];
    rules.push({
      pattern: "TypeScript Types",
      rule: `// Core types used: ${types.slice(0, 5).join(", ")}`,
    });
  }

  return rules;
}

/**
 * Generate .cursorrules format content
 */
function generateCursorRules(code: string): string {
  const rules = extractRules(code);

  const parts: string[] = [];
  parts.push(`# Cursor Rules — Generated by TokenCount\n`);
  parts.push(`> Auto-generated from codebase analysis\n\n`);

  parts.push("## Naming Conventions\n");
  for (const r of rules.filter(rule => rule.pattern.includes("Naming"))) {
    parts.push(`${r.rule}\n`);
  }
  parts.push("\n");

  parts.push("## Code Patterns\n");
  for (const r of rules.filter(rule => rule.pattern.includes("Pattern"))) {
    parts.push(`${r.rule}\n`);
  }
  parts.push("\n");

  parts.push("## Best Practices\n");
  for (const r of rules.filter(rule =>
    rule.pattern.includes("Error") ||
    rule.pattern.includes("Documentation") ||
    rule.pattern.includes("TypeScript")
  )) {
    parts.push(`${r.rule}\n`);
  }

  parts.push("\n---\n");
  parts.push("*Generated by TokenCount — AI Context Optimizer*\n");

  return parts.join("");
}

