#!/usr/bin/env node
// @ts-check
/**
 * Generate one Raycast command per section from src/sections.json.
 *
 * Writes a thin `src/section-{slug}.tsx` wrapper for each section and rewrites
 * the section command entries in package.json. Idempotent: re-run after editing
 * the registry. Non-section commands in package.json are left untouched.
 *
 *   npm run generate:sections
 */

import { readFile, writeFile, readdir, unlink } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src");

/** @typedef {{ slug: string; title: string; keywords?: string[] }} Section */

/** @param {Section} s */
function commandFile(s) {
  return `// Generated by scripts/generate-sections.mjs. Do not edit by hand.
import { fetchSection } from "./api/client";
import { NewsListView } from "./components/NewsListView";

export default function Command() {
  return (
    <NewsListView
      fetchFn={() => fetchSection(${JSON.stringify(s.slug)})}
      searchBarPlaceholder="Search ${s.title}…"
      errorToastTitle="Unable to load ${s.title}"
      emptyTitle="No ${s.title} articles right now"
      emptyDescription="Check back soon. ${s.title} articles from Público will appear here."
    />
  );
}
`;
}

/** @param {Section} s */
function commandEntry(s) {
  return {
    name: `section-${s.slug}`,
    // Command titles are verb-led ("Browse Brazil") to match the core
    // commands. `s.title` stays the bare section name, because it is also
    // interpolated into copy where a verb would read wrong ("Search Brazil…").
    title: `Browse ${s.title}`,
    subtitle: "Público",
    description: `Browse the latest ${s.title} articles from Público`,
    mode: "view",
    ...(s.keywords?.length ? { keywords: s.keywords } : {}),
  };
}

async function main() {
  /** @type {Section[]} */
  const sections = JSON.parse(
    await readFile(join(srcDir, "sections.json"), "utf8"),
  );
  const slugs = new Set(sections.map((s) => s.slug));

  // 1. Write a command component for each section.
  for (const section of sections) {
    await writeFile(
      join(srcDir, `section-${section.slug}.tsx`),
      commandFile(section),
    );
  }

  // 2. Remove stale section-*.tsx files no longer in the registry.
  for (const file of await readdir(srcDir)) {
    const match = file.match(/^section-(.+)\.tsx$/);
    if (match && !slugs.has(match[1])) {
      await unlink(join(srcDir, file));
      console.log(`  removed stale ${file}`);
    }
  }

  // 3. Rewrite section command entries in package.json, preserving the rest.
  const pkgPath = join(root, "package.json");
  const pkg = JSON.parse(await readFile(pkgPath, "utf8"));
  const nonSection = (pkg.commands ?? []).filter(
    (/** @type {{ name: string }} */ c) => !c.name.startsWith("section-"),
  );
  pkg.commands = [...nonSection, ...sections.map(commandEntry)];
  await writeFile(pkgPath, JSON.stringify(pkg, null, 2) + "\n");

  console.log(
    `Generated ${sections.length} section commands ` +
      `(${nonSection.length} core commands preserved).`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
