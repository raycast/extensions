import type { WcagVersion } from "./types";

export const wcagOverviewUrl =
  "https://www.w3.org/WAI/standards-guidelines/wcag/";
export const accessibilityPrinciplesUrl =
  "https://www.w3.org/WAI/fundamentals/accessibility-principles/";
export const wcag2ictUrl = "https://www.w3.org/TR/wcag2ict/";

export function conformanceUrl(version: WcagVersion): string {
  return `https://www.w3.org/WAI/WCAG${version.replace(".", "")}/Understanding/conformance.html`;
}

export function wcagStandardUrl(version: WcagVersion): string {
  return `https://www.w3.org/TR/WCAG${version.replace(".", "")}/`;
}

