import { BIG_ARROWS, OUTLINE_NOTE, SOLID_NOTE, labelledArrow } from "../lib/arrows";

export interface Glyph {
  /** What gets pasted. Multi-line for big arrows; all frames joined by spaces for spinners. */
  text: string;
  name: string;
  aliases?: string[];
  /** Raycast snippet keyword. Only muscle-memory glyphs get one. */
  keyword?: string;
  /** Spinner frames and the delay between them in ms, cli-spinners style. */
  frames?: string[];
  interval?: number;
  /** A caveat shown in the detail pane, e.g. font-dependent width. */
  note?: string;
}

const spinner = (name: string, frames: string[], interval: number, aliases: string[] = []): Glyph => ({
  text: frames.join(" "),
  name,
  frames,
  interval,
  aliases: ["spinner", "loading", ...aliases],
});

