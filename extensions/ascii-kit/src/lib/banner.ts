const HALF: Record<string, string> = { "..": " ", "#.": "▀", ".#": "▄", "##": "█" };

/** Pairs of pixel rows become text rows: top pixel ▀, bottom ▄, both █. */
function toRows(bitmap: string[]): string[] {
  const cols = bitmap[0].length;
  return Array.from({ length: bitmap.length / 2 }, (_, r) =>
    Array.from({ length: cols }, (_, c) => HALF[bitmap[2 * r][c] + bitmap[2 * r + 1][c]]).join(""),
  );
}

const render = (glyphs: Record<string, string[]>) =>
  Object.fromEntries(Object.entries(glyphs).map(([k, v]) => [k, toRows(v)]));

const SMALL = render(GLYPHS);
const TALL = { ...render(TALL_UPPER), ...render(TALL_LOWER) };

export const BANNER_CHARS = Object.keys(GLYPHS);
export const TALL_CHARS = [...Object.keys(TALL_UPPER), ...Object.keys(TALL_LOWER)];

export interface BannerOptions {
  /** `small`: 2 rows, capitals only. `tall`: 3 rows, with lowercase available. */
  size?: "small" | "tall";
  /** Keep lowercase letters lowercase (tall only). Otherwise everything is capitalised. */
  mixedCase?: boolean;
}

const fontFor = (opts: BannerOptions) => (opts.size === "tall" ? TALL : SMALL);
const caseFor = (line: string, opts: BannerOptions) =>
  opts.size === "tall" && opts.mixedCase ? line : line.toUpperCase();

/** Characters the banner has no glyph for, de-duplicated, in input order. Whitespace is fine. */
export function missingBannerChars(input: string, opts: BannerOptions = {}): string[] {
  const font = fontFor(opts);
  const missing = new Set<string>();
  for (const line of splitLines(input)) {
    for (const ch of caseFor(line, opts)) if (!font[ch] && !/\s/.test(ch)) missing.add(ch);
  }
  return [...missing];
}

/** Big letters for headings in plain-text places. Unknown characters are skipped. */
export function renderBanner(input: string, opts: BannerOptions = {}): string {
  const font = fontFor(opts);
  const height = opts.size === "tall" ? 3 : 2;
  return splitLines(input.trim())
    .filter((l) => l.trim())
    .map((line) => {
      const glyphs = [...caseFor(line, opts)].map((ch) => font[ch]).filter(Boolean);
      return Array.from({ length: height }, (_, r) =>
        glyphs
          .map((g) => g[r])
          .join(" ")
          .trimEnd(),
      ).join("\n");
    })
    .join("\n\n");
}
