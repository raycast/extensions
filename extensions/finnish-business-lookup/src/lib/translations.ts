export type TranslationKey = keyof typeof messages;

export function translate(
  key: TranslationKey,
  language: Language,
  values: Record<string, string | number> = {},
): string {
  return messages[key][language === "fi" ? 1 : 0].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    values[name] === undefined ? placeholder : String(values[name]),
  );
}

export function getTranslator(language: Language) {
  return (key: TranslationKey, values?: Record<string, string | number>) => translate(key, language, values);
}
