import Foundation
func check(_ condition: Bool, _ message: String) {
    if !condition { fputs("FAIL: \(message)\n", stderr); exit(1) }
}
let current = URL(fileURLWithPath: "/tmp/current.png")
let previous = URL(fileURLWithPath: "/tmp/previous.png")
let oldest = URL(fileURLWithPath: "/tmp/oldest.png")
var session = BatchSession()
check(session.beginCapture(), "first trigger requests one capture")
check(!session.beginCapture(), "capture cannot be launched twice")
check(!session.selectPrevious(requestedAt: 1), "repeat during rectangle selection adds nothing")
check(!session.captureCompleted(file: current, history: [previous, oldest], completedAt: 10), "holding keeps selection open")
check(!session.beginCapture(), "second trigger can never open another capture")
check(session.files == [current], "initial selection contains the new screenshot")
check(session.selectPrevious(requestedAt: 11), "second tap selects previous existing screenshot")
check(session.files == [current, previous], "two taps select current and preceding screenshot")
check(session.selectPrevious(requestedAt: 12), "third tap selects next older screenshot")
check(session.files == [current, previous, oldest], "selection preserves newest-first order")
check(!session.selectPrevious(requestedAt: 13), "history exhaustion adds no duplicates")
check(session.modifiersReleased(), "release finalizes selection")
check(!session.selectPrevious(requestedAt: 14), "finished group cannot change")
var cancelled = BatchSession()
check(cancelled.beginCapture(), "begin cancelled capture")
check(cancelled.captureCompleted(file: nil, history: [previous]), "Escape ends selection")
check(cancelled.files.isEmpty, "Escape does not copy older screenshots alone")
var earlyRelease = BatchSession()
_ = earlyRelease.beginCapture()
check(!earlyRelease.modifiersReleased(), "release waits for active capture")
check(earlyRelease.captureCompleted(file: current, history: [previous]), "capture completes released selection")
check(earlyRelease.files == [current], "early release keeps normal single-capture behavior")
var delayed = BatchSession()
_ = delayed.beginCapture()
_ = delayed.captureCompleted(file: current, history: [current, previous, previous, oldest], completedAt: 10)
check(!delayed.selectPrevious(requestedAt: 5), "delayed press from drawing is discarded")
check(delayed.selectPrevious(requestedAt: 11), "new tap selects previous")
check(delayed.selectPrevious(requestedAt: 12), "duplicates are excluded from history")
check(delayed.files == [current, previous, oldest], "new image is never included twice")
var fresh = BatchSession()
check(fresh.files.isEmpty && fresh.beginCapture(), "new group does not inherit old selection")
print("PASS: capture once, select older screenshots, exhaustion, cancellation, release, stale events, deduplication")
