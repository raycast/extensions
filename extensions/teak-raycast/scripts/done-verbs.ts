/**
 * Raycast can't import the workspace when it ships, so it carries a generated
 * copy of Teak's done verbs. Regenerate after changing
 * packages/convex/shared/linkCategories.ts:
 *   bun --no-env-file run apps/raycast/scripts/done-verbs.ts --write
 */
import { resolve } from "node:path";
import { LINK_CATEGORY_DONE_VERB } from "../../../packages/convex/shared/linkCategories";

export const DONE_VERBS_PATH = resolve(
  import.meta.dir,
  "../src/lib/doneVerbs.ts"
);

export const renderDoneVerbs = (): string => {
  const verbs = [...new Set(Object.values(LINK_CATEGORY_DONE_VERB))].sort();
  const entries = Object.entries(LINK_CATEGORY_DONE_VERB).sort(([a], [b]) =>
    a.localeCompare(b)
  );
  return [
    "// Generated by apps/raycast/scripts/done-verbs.ts from",
    "// packages/convex/shared/linkCategories.ts. Don't edit.",
    "",
    "/** What a link's done state is called, by the kind of link. */",
    "export type DoneVerb =",
    ...verbs.map(
      (verb, index) =>
        `  | "${verb}"${index === verbs.length - 1 ? ";" : ""}`
    ),
    "",
    "export const DONE_VERB_BY_CATEGORY: Record<string, DoneVerb> = {",
    ...entries.map(([category, verb]) => `  ${category}: "${verb}",`),
    "};",
    "",
  ].join("\n");
};

if (import.meta.main) {
  if (process.argv.includes("--write")) {
    await Bun.write(DONE_VERBS_PATH, renderDoneVerbs());
    console.log(`Wrote ${DONE_VERBS_PATH}`);
  } else {
    process.stdout.write(renderDoneVerbs());
  }
}
