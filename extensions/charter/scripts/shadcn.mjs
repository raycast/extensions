// Pulls the chart blocks for each shadcn chart family from ui.shadcn.com: the
// block names from the docs page, then each block's source from the registry.
// Writes src/data/shadcn.ts. Needs the network. Run by hand: npm run shadcn.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const root = fileURLToPath(new URL("..", import.meta.url));
const FAMILIES = ["area", "bar", "line", "pie", "radar", "radial"];
const DOCS = "https://ui.shadcn.com/charts";
const REGISTRY = "https://ui.shadcn.com/r/styles/new-york-v4";

async function text(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return response.text();
}

/** "chart-bar-label-custom" becomes "Label Custom". */
function titleFromName(name, family) {
  return name
    .replace(`chart-${family}-`, "")
    .split("-")
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join(" ");
}

/** "Bar Chart - Horizontal" becomes "Horizontal"; a bare "Bar Chart" is the plain one. */
function titleOf(source, name, family) {
  const match = source.match(/<CardTitle>([^<]+)<\/CardTitle>/);
  const full = match ? match[1].trim() : "";
  const suffix = full.split(" - ")[1]?.trim();
  return suffix || (full ? "Default" : titleFromName(name, family));
}

/** The registry ships its own import paths; the CLI rewrites them on install, so the copy does too. */
function portable(source) {
  return source.replaceAll("@/registry/new-york-v4/", "@/components/");
}

const out = {};
for (const family of FAMILIES) {
  const page = await text(`${DOCS}/${family}`);
  const names = [...new Set(page.match(new RegExp(`chart-${family}-[a-z-]+`, "g")) ?? [])].filter(
    (name) => !name.endsWith("-"),
  );
  if (names.length === 0) throw new Error(`no blocks found for ${family}`);
  const blocks = [];
  for (const name of names) {
    const item = JSON.parse(await text(`${REGISTRY}/${name}.json`));
    const source = item.files?.[0]?.content;
    if (!source) throw new Error(`${name} has no source in the registry`);
    blocks.push({ name, title: titleOf(source, name, family), source: portable(source) });
  }
  // Two cards can share a title (radar's grid-circle and grid-circle-no-lines); the name tells them apart.
  const counts = new Map();
  for (const block of blocks) counts.set(block.title, (counts.get(block.title) ?? 0) + 1);
  for (const block of blocks) {
    if (counts.get(block.title) > 1) block.title = titleFromName(block.name, family);
  }
  out[family] = blocks;
  console.log(`${family}: ${blocks.map((block) => block.title).join(", ")}`);
}

const date = new Date().toISOString().slice(0, 10);
const body = FAMILIES.map(
  (family) =>
    `  ${family}: [\n` +
    out[family]
      .map(
        (block) =>
          `    {\n      name: ${JSON.stringify(block.name)},\n      title: ${JSON.stringify(block.title)},\n      source: ${JSON.stringify(block.source)},\n    },\n`,
      )
      .join("") +
    `  ],\n`,
).join("");
const target = join(root, "src", "data", "shadcn.ts");
const raw =
  `// Generated by scripts/shadcn.mjs from ui.shadcn.com on ${date}. Do not edit by hand.\n` +
  `// The block sources are shadcn/ui (MIT, https://github.com/shadcn-ui/ui), import paths rewritten as the CLI does.\n` +
  `import type { ShadcnBlock, ShadcnFamily } from "../lib/catalog";\n\n` +
  `export const SHADCN_BLOCKS: Record<ShadcnFamily, ShadcnBlock[]> = {\n${body}};\n`;
const config = (await resolveConfig(target)) ?? {};
writeFileSync(target, await format(raw, { ...config, filepath: target }));
console.log(`wrote src/data/shadcn.ts`);
