// Regenerates src/lib/layout-data.ts from the keyboard layouts installed on this Mac.
// Run: swift scripts/gen-layouts.swift > src/lib/layout-data.ts

import Carbon
import Foundation

/// Printable ANSI keys in keyboard order, as macOS virtual key codes.
let keyCodes: [UInt16] = [
    50, 18, 19, 20, 21, 23, 22, 26, 28, 25, 29, 27, 24,
    12, 13, 14, 15, 17, 16, 32, 34, 31, 35, 33, 30, 42,
    0, 1, 2, 3, 5, 4, 38, 40, 37, 41, 39,
    6, 7, 8, 9, 11, 45, 46, 43, 47, 44,
]

let layouts: [(name: String, id: String)] = [
    ("us", "com.apple.keylayout.US"),
    ("persian", "com.apple.keylayout.Persian"),
    ("isiri2901", "com.apple.keylayout.Persian-ISIRI2901"),
]

func character(_ data: Data, _ code: UInt16, shift: Bool) -> String {
    var dead: UInt32 = 0
    var length = 0
    var chars = [UniChar](repeating: 0, count: 4)
    let modifiers: UInt32 = shift ? UInt32(shiftKey >> 8) & 0xFF : 0
    let status = data.withUnsafeBytes { raw -> OSStatus in
        UCKeyTranslate(raw.bindMemory(to: UCKeyboardLayout.self).baseAddress!,
                       code, UInt16(kUCKeyActionDown), modifiers,
                       UInt32(LMGetKbdType()), OptionBits(1 << kUCKeyTranslateNoDeadKeysBit),
                       &dead, 4, &length, &chars)
    }
    return status == noErr ? String(utf16CodeUnits: chars, count: length) : ""
}

func json(_ s: String) -> String {
    let data = try! JSONSerialization.data(withJSONObject: [s], options: [.withoutEscapingSlashes])
    let array = String(data: data, encoding: .utf8)!
    return String(array.dropFirst().dropLast())
}

print("// Generated by scripts/gen-layouts.swift. Do not edit by hand.")
print("// Each layout lists the characters for the same physical keys, unshifted then shifted.\n")
print("export const LAYOUT_DATA = {")
for layout in layouts {
    let filter = [kTISPropertyInputSourceID as String: layout.id] as CFDictionary
    guard let source = (TISCreateInputSourceList(filter, true).takeRetainedValue() as! [TISInputSource]).first,
          let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else {
        FileHandle.standardError.write("missing layout \(layout.id)\n".data(using: .utf8)!)
        exit(1)
    }
    let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue() as Data
    let normal = keyCodes.map { json(character(data, $0, shift: false)) }.joined(separator: ", ")
    let shifted = keyCodes.map { json(character(data, $0, shift: true)) }.joined(separator: ", ")
    print("  \(layout.name): {")
    print("    normal: [\(normal)],")
    print("    shift: [\(shifted)],")
    print("  },")
}
print("} as const;")
