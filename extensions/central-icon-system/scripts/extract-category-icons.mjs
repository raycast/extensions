#!/usr/bin/env node
/**
 * Extract the category → SVG mapping from centralicons.com's category menu.
 *
 * The site illustrates each category with a specific icon, and those choices are
 * editorial — they are NOT simply the first icon in the category. An earlier
 * heuristic ("use the first icon") produced visibly wrong glyphs, and matching
 * path data back to icon names was worse: three categories found no match and
 * two matched the wrong icon, because several categories are illustrated with
 * icons drawn at a different stroke weight than the one we bundle.
 *
 * So the markup is the source of truth. Paste the menu's inner HTML into
 * `scripts/data/category-menu.html` and run this to regenerate
 * `src/lib/category-icons.ts`.
 *
 * Usage: node scripts/extract-category-icons.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "scripts", "data", "category-menu.html");
const OUTPUT = path.join(ROOT, "src", "lib", "category-icons.ts");

/** Undo the HTML entities that appear in category labels (`&amp;` → `&`). */
function decode(value) {
  return value
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
}

function main() {
  if (!fs.existsSync(SOURCE)) {
    console.error(`Missing ${path.relative(ROOT, SOURCE)}.`);
    console.error("Copy the category menu's inner HTML from centralicons.com into that file.");
    process.exit(1);
  }

  const html = fs.readFileSync(SOURCE, "utf8");

  // Each entry is `<div … aria-label="Category"><svg …>…</svg>Label</div>`.
  const entries = new Map();
  const itemPattern = /aria-label="([^"]+)"[^>]*>(<svg[\s\S]*?<\/svg>)/g;

  let match;
  while ((match = itemPattern.exec(html)) !== null) {
    const label = decode(match[1]);
    let svg = match[2];

    // Normalize to the same shape the icon blobs use: 24-unit viewBox, no
    // intrinsic size (Raycast scales it), no aria noise.
    svg = svg
      .replace(/\s*aria-hidden="[^"]*"/g, "")
      .replace(/\s*width="[^"]*"/, "")
      .replace(/\s*height="[^"]*"/, "")
      .replace(/></g, "><")
      .trim();

    entries.set(label, svg);
  }

  if (entries.size === 0) {
    console.error("No category entries found — is the HTML the menu's inner markup?");
    process.exit(1);
  }

  const lines = [
    "/**",
    " * Category icons, lifted verbatim from centralicons.com's category menu.",
    " *",
    " * Generated by `scripts/extract-category-icons.mjs` — do not edit by hand.",
    " * These are the site's own editorial choices; they are not derivable from the",
    " * icon data (several are drawn at a stroke weight we do not bundle), so the",
    " * markup is copied rather than looked up.",
    " */",
    "",
    "export const CATEGORY_ICONS: Record<string, string> = {",
  ];

  for (const [label, svg] of [...entries].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  ${JSON.stringify(label)}: ${JSON.stringify(svg)},`);
  }

  lines.push("};", "");
  fs.writeFileSync(OUTPUT, lines.join("\n"));

  console.log(`Wrote ${entries.size} category icons → ${path.relative(ROOT, OUTPUT)}`);
  for (const label of [...entries.keys()].sort()) console.log(`  ${label}`);
}

main();
