export function getNearestPhysicalColor(targetHex: string, system: "RAL" | "COPIC" | "PRISMACOLOR"): PhysicalColor {
  const dataset = system === "RAL" ? RAL_COLORS : system === "COPIC" ? COPIC_COLORS : PRISMACOLOR_COLORS;

  let nearest: PhysicalColor = dataset[0];
  let minDistance = Infinity;

  const rgb1 = hexToRgb(targetHex);

  for (const color of dataset) {
    const rgb2 = hexToRgb(color.hex);

    // Euclidean distance in RGB space
    const distance = Math.sqrt(
      Math.pow(rgb2.r - rgb1.r, 2) + Math.pow(rgb2.g - rgb1.g, 2) + Math.pow(rgb2.b - rgb1.b, 2),
    );

    if (distance < minDistance) {
      minDistance = distance;
      nearest = color;
    }
  }

  return nearest;
}
