import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(root, "src", "data", "default-shortcuts");
const outputPath = path.join(root, "src", "data", "generated-default-shortcuts.ts");

const files = (await readdir(dataDir)).filter((file) => file.endsWith(".json")).sort();
const datasets = [];

for (const file of files) {
  const raw = await readFile(path.join(dataDir, file), "utf8");
  const parsed = JSON.parse(raw);
  datasets.push(parsed);
}

const output = `// This file is generated by scripts/generate-default-shortcuts.mjs.
// Add or edit JSON files in src/data/default-shortcuts, then run npm run generate-data.

import type { DefaultShortcutDataset } from "../types/shortcut";

export const defaultShortcutDatasets: DefaultShortcutDataset[] = ${JSON.stringify(datasets, null, 2)};
`;

await writeFile(outputPath, output);
