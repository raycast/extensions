/** osascript -l JavaScript helper.js <dir> selftest — checks every macOS API used here. */
function selftest() {
  var out = [];
  function step(name, fn) {
    try {
      var r = fn();
      out.push("OK   " + name + (r !== undefined ? " → " + r : ""));
    } catch (e) {
      out.push("FAIL " + name + " → " + e);
    }
  }
  step("pasteboard types", function () {
    return JSON.stringify((ObjC.deepUnwrap(pb.types) || []).slice(0, 4));
  });
  step("front app", function () {
    return frontApp().name;
  });
  step("read/write json", function () {
    writeJSON(p("selftest.json"), { ok: true });
    var ok = readJSON(p("selftest.json"), {}).ok;
    removeFile(p("selftest.json"));
    return ok;
  });
  step("lock", function () {
    return withLock(function () {
      return "locked";
    });
  });
  step("history", function () {
    return readHistory().length + " items";
  });
  step("color swatch", function () {
    return swatch([1, 0, 0]).isNil() ? "nil" : "image";
  });
  step("image save + thumbnail", function () {
    var e = saveImage(swatch([0, 0.5, 1]));
    if (!e) return "save failed";
    var t = thumbnail(e.imagePath);
    removeFile(e.imagePath);
    if (!t) return "thumbnail failed";
    return e.text + " → " + Math.round(t.size.width) + "×" + Math.round(t.size.height);
  });
  step("last image in history", function () {
    var imgs = readHistory().filter(function (x) {
      return x.kind === "image";
    });
    if (!imgs.length) return "none yet (copy a screenshot with ⌃⇧⌘4 to test)";
    return exists(imgs[0].imagePath) ? "file ok, thumbnail " + (thumbnail(imgs[0].imagePath) ? "ok" : "FAILED") : "file missing";
  });
  step("build main menu", function () {
    return buildMenu("main").numberOfItems + " items";
  });
  step("mouse location", function () {
    var m = $.NSEvent.mouseLocation;
    return Math.round(m.x) + "," + Math.round(m.y);
  });
  step("pump events", function () {
    pump(0.01);
    return "ok";
  });
  return out.join("\n");
}

function run(argv) {
  init(argv[0]);
  if (argv[1] === "selftest") return selftest();
  if (argv[1] === "popup") {
    // Manual test: show a menu right away
    writeJSON(p("request.json"), { id: "test", cmd: "popup", menu: argv[2] || "main" });
    handleRequest();
    return JSON.stringify(readJSON(p("response.json"), {}));
  }
  writeJSON(p("helper.pid.json"), { version: HELPER_VERSION, startedAt: Date.now() });
  log("helper v" + HELPER_VERSION + " started");

  var last = pb.changeCount;
  var started = Date.now();
  // Exit after about an hour; launchd restarts us immediately (keeps memory flat).
  while (Date.now() - started < 3600 * 1000) {
    pump(0.05);
    try {
      if (exists(p("request.json"))) handleRequest();
    } catch (e) {
      log("request failed: " + e);
    }
    var cc = pb.changeCount;
    if (cc !== last) {
      last = cc;
      try {
        capture(cc);
      } catch (e2) {
        log("capture failed: " + e2);
      }
    }
  }
}

