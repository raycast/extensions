// Charon Clipboard helper — a resident process that runs on macOS's built-in
// osascript (JavaScript for Automation). No compiled binaries are involved.
//
//   osascript -l JavaScript helper.js <supportDir> [selftest | popup <menu>]
//
// It does the parts of a Clipy-style clipboard manager that the Raycast API cannot:
//   1. Watches the pasteboard (NSPasteboard.changeCount every 50 ms) and records
//      text, rich text (HTML/RTF), images and files into history.json.
//   2. Shows a native NSMenu at the mouse cursor when Raycast asks for it.
//   3. Writes the chosen item back to the pasteboard with all of its types.
//      (Raycast sends the ⌘V keystroke afterwards.)
//
// It talks to the Raycast extension through files in supportDir:
//   config.json    Raycast → helper  preferences
//   request.json   Raycast → helper  {id, cmd: "popup" | "paste" | "ping", ...}
//   response.json  helper → Raycast  {id, action: "paste" | "none" | "pong"}
//   history.json   shared            guarded by the history.lock directory
//   selfpaste.json Raycast → helper  marks a paste performed by Raycast itself
/* global ObjC, $, delay */

var HELPER_VERSION = "6";

var DEFAULT_CONFIG = {
  maxHistory: 30,
  itemsInline: 0,
  itemsPerFolder: 10,
  maxTitleLength: 20,
  numbered: true,
  numericShortcuts: true,
  tooltip: true,
  tooltipLength: 200,
  imagePreview: true,
  colorPreview: true,
  confirmClear: true,
  reorder: true,
  dedupe: true,
  types: { rich: true, image: true, file: true },
  excluded: [],
  deeplinkBase: "raycast://extensions/unz47/charon-clipboard",
};

var SKIP_TYPES = [
  "org.nspasteboard.ConcealedType",
  "org.nspasteboard.TransientType",
  "org.nspasteboard.AutoGeneratedType",
  "com.agilebits.onepassword",
  "com.typeit4me.clipping",
  "de.petermaurer.TransientPasteboardType",
  "Pasteboard generator type",
  "net.antelle.keeweb",
];
var IMAGE_TYPES = ["public.png", "public.tiff", "public.jpeg", "com.compuserve.gif", "public.heic"];

// ---------------------------------------------------------------- pure helpers (unit-tested with node)

function mergeConfig(raw) {
  var c = JSON.parse(JSON.stringify(DEFAULT_CONFIG));
  if (!raw || typeof raw !== "object") return c;
  Object.keys(raw).forEach(function (k) {
    if (k === "types" && raw.types && typeof raw.types === "object") {
      Object.keys(raw.types).forEach(function (t) {
        c.types[t] = raw.types[t];
      });
    } else if (raw[k] !== undefined && raw[k] !== null) {
      c[k] = raw[k];
    }
  });
  return c;
}

/** Like Clipy: collapse newlines and runs of spaces, then truncate. */
function menuTitle(text, max) {
  var t = String(text || "")
    .replace(/[\r\n\t]+/g, " ")
    .replace(/ {2,}/g, " ")
    .trim();
  if (!t) t = "(Blank)";
  var chars = Array.from(t);
  return chars.length > max ? chars.slice(0, max).join("") + "..." : t;
}

function colorCode(text) {
  var m = /^\s*#?([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\s*$/.exec(String(text || ""));
  if (!m) return null;
  var c = m[1];
  if (c.length === 3)
    c = c
      .split("")
      .map(function (x) {
        return x + x;
      })
      .join("");
  return [parseInt(c.substr(0, 2), 16) / 255, parseInt(c.substr(2, 2), 16) / 255, parseInt(c.substr(4, 2), 16) / 255];
}

/** Split history into inline items and numbered folders (1 - 10, 11 - 20, ...). */
function layoutHistory(history, cfg) {
  var inline = history.slice(0, cfg.itemsInline);
  var rest = history.slice(cfg.itemsInline);
  var folders = [];
  var per = Math.max(1, cfg.itemsPerFolder);
  for (var i = 0; i < rest.length; i += per) {
    var start = cfg.itemsInline + i + 1;
    folders.push({ title: start + " - " + (start + per - 1), start: start, items: rest.slice(i, i + per) });
  }
  return { inline: inline, folders: folders };
}

/** Key equivalent for the n-th item in a menu: 1, 2, ..., 9, 0, then none. */
function numericKey(indexInMenu) {
  return indexInMenu < 10 ? String((indexInMenu + 1) % 10) : "";
}

/**
 * Should a copy be recorded as an image? True when the pasteboard has image data and its
 * text is missing or just a single URL / path (e.g. Safari's "Copy Image" also puts the URL).
 */
function preferImage(types, str) {
  var hasImage = IMAGE_TYPES.some(function (t) {
    return types.indexOf(t) !== -1;
  });
  if (!hasImage) return false;
  var t = String(str || "").trim();
  if (!t) return true;
  return !/[\r\n]/.test(t) && /^(https?:|file:|data:image\/|\/)/i.test(t);
}

function entryKey(e) {
  if (e.kind === "file") return "file:" + (e.files || []).join("\n");
  if (e.kind === "image") return "image:" + (e.imageBytes || 0) + ":" + e.text;
  return "text:" + e.text;
}

/**
 * Put a new entry on top of the history. Returns the items that fell off.
 * `same(existing, entry)` can confirm a duplicate (used to compare image bytes).
 */
function pushEntry(history, entry, cfg, same) {
  var next = history.slice();
  if (cfg.dedupe) {
    var key = entryKey(entry);
    var dupIdx = -1;
    for (var i = 0; i < next.length; i++) {
      if (entryKey(next[i]) === key && (!same || same(next[i], entry))) {
        dupIdx = i;
        break;
      }
    }
    if (dupIdx >= 0) {
      var dup = next.splice(dupIdx, 1)[0];
      entry.id = dup.id;
      if (dup.imagePath && entry.imagePath && dup.imagePath !== entry.imagePath) entry.dropImage = dup.imagePath;
    }
  }
  next.unshift(entry);
  var removed = next.slice(cfg.maxHistory);
  return { history: next.slice(0, cfg.maxHistory), removed: removed };
}

function moveToTop(history, id, now) {
  var idx = -1;
  for (var i = 0; i < history.length; i++) if (history[i].id === id) idx = i;
  if (idx < 0) return history;
  var next = history.slice();
  var item = next.splice(idx, 1)[0];
  item.copiedAt = now;
  next.unshift(item);
  return next;
}

function isExcluded(cfg, bundleId, appName) {
  var list = cfg.excluded || [];
  for (var i = 0; i < list.length; i++) {
    var x = String(list[i]).trim().toLowerCase();
    if (!x) continue;
    if (x === String(bundleId || "").toLowerCase() || x === String(appName || "").toLowerCase()) return true;
  }
  return false;
}

// ---------------------------------------------------------------- macOS side

var DIR, fm, pb, ws, app, TARGET, RUNLOOP_MODE, UTF8, PB_STRING;
var cfg = DEFAULT_CONFIG;
var cfgStamp = -1;
var picked = null;
var menuTable = [];
var selfMarker = null;

function p(name) {
  return DIR + "/" + name;
}

function log(msg) {
  try {
    var line = new Date().toISOString() + " " + msg + "\n";
    var path = p("helper.log");
    if (!fm.fileExistsAtPath(path)) fm.createFileAtPathContentsAttributes(path, $.NSData.data, $());
    var fh = $.NSFileHandle.fileHandleForWritingAtPath(path);
    if (fh.isNil()) return;
    fh.seekToEndOfFile;
    fh.writeData($(line).dataUsingEncoding(UTF8));
    fh.closeFile;
  } catch (e) {
    // ignore
  }
}

function exists(path) {
  return fm.fileExistsAtPath(path);
}

function readJSON(path, fallback) {
  var s = $.NSString.stringWithContentsOfFileEncodingError(path, UTF8, $());
  if (!s || s.isNil()) return fallback;
  try {
    return JSON.parse(ObjC.unwrap(s));
  } catch (e) {
    return fallback;
  }
}

function writeJSON(path, obj) {
  $(JSON.stringify(obj, null, 2)).writeToFileAtomicallyEncodingError(path, true, UTF8, $());
}

function removeFile(path) {
  if (path && exists(path)) fm.removeItemAtPathError(path, $());
}

function mtime(path) {
  var attrs = fm.attributesOfItemAtPathError(path, $());
  if (!attrs || attrs.isNil()) return -1;
  var d = attrs.fileModificationDate;
  return d && !d.isNil() ? d.timeIntervalSince1970 : -1;
}

function loadConfig() {
  var m = mtime(p("config.json"));
  if (m === cfgStamp) return;
  cfgStamp = m;
  cfg = mergeConfig(readJSON(p("config.json"), null));
}

function withLock(fn) {
  var lock = p("history.lock");
  for (var i = 0; i < 100; i++) {
    if (fm.createDirectoryAtPathWithIntermediateDirectoriesAttributesError(lock, false, $(), $())) {
      try {
        return fn();
      } finally {
        fm.removeItemAtPathError(lock, $());
      }
    }
    var m = mtime(lock);
    if (m > 0 && Date.now() / 1000 - m > 3) fm.removeItemAtPathError(lock, $()); // stale lock
    delay(0.02);
  }
  log("lock timeout; continuing without lock");
  return fn();
}

function readHistory() {
  var h = readJSON(p("history.json"), []);
  return Array.isArray(h) ? h : [];
}

function saveHistory(h, removed) {
  writeJSON(p("history.json"), h);
  (removed || []).forEach(function (r) {
    if (r.imagePath) removeFile(r.imagePath);
  });
}

function uuid() {
  return ObjC.unwrap($.NSUUID.UUID.UUIDString).toLowerCase();
}

function frontApp() {
  var a = ws.frontmostApplication;
  if (!a || a.isNil()) return { bundleId: "", name: "", ref: null };
  return { bundleId: ObjC.unwrap(a.bundleIdentifier) || "", name: ObjC.unwrap(a.localizedName) || "", ref: a };
}

// ---------------------------------------------------------------- 1. recording

/** Two image entries are duplicates only if their PNG files are byte-for-byte equal. */
function sameImageBytes(a, b) {
  if (a.kind !== "image" || b.kind !== "image") return true;
  if (!a.imagePath || !b.imagePath) return false;
  var da = $.NSData.dataWithContentsOfFile($(a.imagePath));
  var db = $.NSData.dataWithContentsOfFile($(b.imagePath));
  return !!(da && db && !da.isNil() && !db.isNil() && da.isEqualToData(db));
}

/** Save the pasteboard image as PNG and return a history entry (or null). */
function saveImage(source) {
  var img = source || $.NSImage.alloc.initWithPasteboard(pb);
  if (!img || img.isNil()) return null;
  var tiff = img.TIFFRepresentation;
  if (!tiff || tiff.isNil()) return null;
  var rep = $.NSBitmapImageRep.imageRepWithData(tiff);
  if (!rep || rep.isNil()) return null;
  var png = rep.representationUsingTypeProperties(4 /* NSBitmapImageFileTypePNG */, $.NSDictionary.dictionary);
  if (!png || png.isNil()) return null;
  if (!exists(p("images"))) fm.createDirectoryAtPathWithIntermediateDirectoriesAttributesError(p("images"), true, $(), $());
  var id = uuid();
  var path = p("images/" + id + ".png");
  if (!png.writeToFileAtomically($(path), true)) return null;
  return {
    id: id,
    kind: "image",
    imagePath: path,
    imageBytes: png.length,
    text: "Image " + rep.pixelsWide + "×" + rep.pixelsHigh,
  };
}

function capture(cc) {
  loadConfig();

  // Changes we (or Raycast) made ourselves in order to paste
  if (selfMarker && selfMarker.cc === cc) {
    var sid = selfMarker.id;
    selfMarker = null;
    if (sid === "__skip__") return;
    if (sid) {
      if (cfg.reorder) withLock(function () {
        saveHistory(moveToTop(readHistory(), sid, Date.now()));
      });
      return;
    }
  }
  var rm = readJSON(p("selfpaste.json"), null);
  if (rm) {
    removeFile(p("selfpaste.json"));
    if (rm.id && Date.now() - rm.at < 3000) {
      if (cfg.reorder) withLock(function () {
        saveHistory(moveToTop(readHistory(), rm.id, Date.now()));
      });
      return;
    }
  }

  var types = ObjC.deepUnwrap(pb.types) || [];
  if (!types.length) return;
  for (var i = 0; i < SKIP_TYPES.length; i++) if (types.indexOf(SKIP_TYPES[i]) !== -1) return;

  var front = frontApp();
  if (isExcluded(cfg, front.bundleId, front.name)) return;

  var entry = null;
  var str = ObjC.unwrap(pb.stringForType(PB_STRING));

  if (cfg.types.file && types.indexOf("public.file-url") !== -1) {
    var urls = pb.readObjectsForClassesOptions($.NSArray.arrayWithObject($.NSURL), $());
    var files = [];
    if (urls && !urls.isNil()) {
      for (var j = 0; j < urls.count; j++) {
        var u = urls.objectAtIndex(j);
        if (u.isFileURL) files.push(ObjC.unwrap(u.path));
      }
    }
    if (files.length) entry = { kind: "file", files: files, text: files.join("\n") };
  }

  if (!entry && cfg.types.image && preferImage(types, str)) entry = saveImage();

  if (!entry && str && String(str).trim()) {
    entry = { kind: "text", text: String(str) };
    if (cfg.types.rich) {
      var html = ObjC.unwrap(pb.stringForType("public.html"));
      if (html && html.length < 2000000) entry.html = String(html);
      var rtf = pb.dataForType("public.rtf");
      if (rtf && !rtf.isNil() && rtf.length < 2000000) entry.rtf = ObjC.unwrap(rtf.base64EncodedStringWithOptions(0));
    }
  }

  if (!entry && cfg.types.image && preferImage(types, "")) entry = saveImage();

  if (!entry) return;
  entry.id = entry.id || uuid();
  entry.copiedAt = Date.now();
  entry.app = front.name;

  withLock(function () {
    var r = pushEntry(readHistory(), entry, cfg, sameImageBytes);
    if (entry.dropImage) {
      removeFile(entry.dropImage);
      delete entry.dropImage;
    }
    saveHistory(r.history, r.removed);
  });
}

// ---------------------------------------------------------------- 3. writing back

function writeEntryToPasteboard(entry, plain) {
  pb.clearContents;
  if (entry.kind === "file" && !plain && entry.files && entry.files.length) {
    var arr = $.NSMutableArray.array;
    entry.files.forEach(function (f) {
      arr.addObject($.NSURL.fileURLWithPath(f));
    });
    pb.writeObjects(arr);
  } else if (entry.kind === "image" && !plain && entry.imagePath) {
    var im = $.NSImage.alloc.initWithContentsOfFile(entry.imagePath);
    if (im && !im.isNil()) pb.writeObjects($.NSArray.arrayWithObject(im));
  } else {
    pb.setStringForType($(entry.text), PB_STRING);
    if (!plain) {
      if (entry.html) pb.setStringForType($(entry.html), "public.html");
      if (entry.rtf) {
        var d = $.NSData.alloc.initWithBase64EncodedStringOptions($(entry.rtf), 0);
        if (d && !d.isNil()) pb.setDataForType(d, "public.rtf");
      }
    }
  }
  selfMarker = { cc: pb.changeCount, id: entry.id || null };
}

function findHistory(id) {
  var h = readHistory();
  for (var i = 0; i < h.length; i++) if (h[i].id === id) return h[i];
  return null;
}

function deleteHistory(id) {
  withLock(function () {
    var h = readHistory();
    var removed = h.filter(function (x) {
      return x.id === id;
    });
    saveHistory(
      h.filter(function (x) {
        return x.id !== id;
      }),
      removed,
    );
  });
}

function clearHistory() {
  withLock(function () {
    saveHistory([], readHistory());
  });
}

// ---------------------------------------------------------------- 2. menus

function registerTarget() {
  ObjC.registerSubclass({
    name: "ClipyLikeTarget",
    superclass: "NSObject",
    methods: {
      "pick:": {
        types: ["void", ["id"]],
        implementation: function (sender) {
          picked = { tag: sender.tag, mods: $.NSEvent.modifierFlags };
        },
      },
    },
  });
  TARGET = $.ClipyLikeTarget.alloc.init;
}

function addItem(menu, title, action, opts) {
  opts = opts || {};
  var item = $.NSMenuItem.alloc.initWithTitleActionKeyEquivalent($(title), action ? "pick:" : null, $(opts.key || ""));
  if (action) {
    item.target = TARGET;
    item.tag = menuTable.length;
    menuTable.push(action);
  } else {
    item.enabled = false;
  }
  if (opts.key) item.keyEquivalentModifierMask = 0;
  if (opts.tooltip) item.toolTip = $(opts.tooltip);
  if (opts.image) item.image = opts.image;
  menu.addItem(item);
  return item;
}

function makeSize(w, h) {
  return typeof $.NSMakeSize === "function" ? $.NSMakeSize(w, h) : { width: w, height: h };
}

function makeRect(x, y, w, h) {
  return typeof $.NSMakeRect === "function"
    ? $.NSMakeRect(x, y, w, h)
    : { origin: { x: x, y: y }, size: { width: w, height: h } };
}

function swatch(rgb) {
  var size = makeSize(14, 14);
  var img = $.NSImage.alloc.initWithSize(size);
  img.lockFocus;
  $.NSColor.colorWithSRGBRedGreenBlueAlpha(rgb[0], rgb[1], rgb[2], 1).setFill;
  $.NSBezierPath.fillRect(makeRect(0, 0, 14, 14));
  $.NSColor.colorWithWhiteAlpha(0, 0.25).setStroke;
  $.NSBezierPath.strokeRect(makeRect(0.5, 0.5, 13, 13));
  img.unlockFocus;
  return img;
}

/** Thumbnail like Clipy's (fits in 100 × 32 pt). */
function thumbnail(path) {
  var im = $.NSImage.alloc.initWithContentsOfFile($(path));
  if (!im || im.isNil()) return null;
  var w = 0;
  var h = 0;
  try {
    var reps = im.representations;
    if (reps && reps.count > 0) {
      w = reps.objectAtIndex(0).pixelsWide;
      h = reps.objectAtIndex(0).pixelsHigh;
    }
  } catch (e) {
    // fall through
  }
  if (!w || !h) {
    var s = im.size;
    w = s.width;
    h = s.height;
  }
  if (!w || !h) return null;
  var scale = Math.min(100 / w, 32 / h, 1);
  im.setSize(makeSize(Math.max(1, Math.round(w * scale)), Math.max(1, Math.round(h * scale))));
  return im;
}

function historyMenuItem(menu, entry, number, indexInMenu) {
  var title = menuTitle(entry.text, cfg.maxTitleLength);
  if (cfg.numbered) title = number + ". " + title;
  var opts = {};
  if (cfg.numericShortcuts) opts.key = numericKey(indexInMenu);
  if (cfg.tooltip && entry.kind !== "image") opts.tooltip = Array.from(entry.text).slice(0, cfg.tooltipLength).join("");
  if (entry.kind === "image" && cfg.imagePreview && entry.imagePath) {
    opts.image = thumbnail(entry.imagePath);
    // Like Clipy, an image item shows just its thumbnail (and number)
    if (opts.image) title = cfg.numbered ? number + "." : "";
  } else if (cfg.colorPreview) {
    var rgb = colorCode(entry.text);
    if (rgb) opts.image = swatch(rgb);
  }
  addItem(menu, title, { type: "history", id: entry.id }, opts);
}

function addHistorySection(menu) {
  var history = readHistory();
  addItem(menu, "History", null);
  var layout = layoutHistory(history, cfg);
  layout.inline.forEach(function (e, i) {
    historyMenuItem(menu, e, i + 1, i);
  });
  layout.folders.forEach(function (f) {
    var sub = $.NSMenu.alloc.initWithTitle($(f.title));
    sub.autoenablesItems = false;
    f.items.forEach(function (e, i) {
      historyMenuItem(sub, e, f.start + i, i);
    });
    var holder = $.NSMenuItem.alloc.initWithTitleActionKeyEquivalent($(f.title), null, $(""));
    holder.submenu = sub;
    menu.addItem(holder);
  });
}

function snippetFolderMenu(folder) {
  var sub = $.NSMenu.alloc.initWithTitle($(folder.title));
  sub.autoenablesItems = false;
  if (!folder.snippets.length) addItem(sub, "(No Snippets)", null);
  folder.snippets.forEach(function (s) {
    addItem(
      sub,
      s.title,
      { type: "snippet", folderId: folder.id, snippetId: s.id },
      { tooltip: cfg.tooltip ? Array.from(s.content).slice(0, cfg.tooltipLength).join("") : "" },
    );
  });
  return sub;
}

function addSnippetSection(menu) {
  var folders = (readJSON(p("snippets.json"), []) || []).filter(function (f) {
    return f.enabled !== false;
  });
  addItem(menu, "Snippets", null);
  folders.forEach(function (f) {
    var holder = $.NSMenuItem.alloc.initWithTitleActionKeyEquivalent($(f.title), null, $(""));
    holder.submenu = snippetFolderMenu(f);
    menu.addItem(holder);
  });
}

function buildMenu(kind, folderName) {
  menuTable = [];
  var menu = $.NSMenu.alloc.initWithTitle($("Clipy"));
  menu.autoenablesItems = false;
  if (kind === "folder") {
    var folders = readJSON(p("snippets.json"), []) || [];
    var f = folders.filter(function (x) {
      return x.title === folderName;
    })[0];
    if (!f) {
      addItem(menu, "Folder \"" + folderName + "\" not found", null);
      return menu;
    }
    var sub = snippetFolderMenu(f);
    return sub;
  }
  if (kind === "main" || kind === "history") addHistorySection(menu);
  if (kind === "main") menu.addItem($.NSMenuItem.separatorItem);
  if (kind === "main" || kind === "snippets") addSnippetSection(menu);
  if (kind === "main" || kind === "history") {
    menu.addItem($.NSMenuItem.separatorItem);
    addItem(menu, "Clear History", { type: "clear" });
  }
  if (kind === "main") {
    addItem(menu, "Edit Snippets…", { type: "open", path: "/manage-snippets" });
    addItem(menu, "Preferences…", { type: "open", path: "/open-preferences" });
  }
  return menu;
}

function pump(seconds) {
  var until = $.NSDate.dateWithTimeIntervalSinceNow(seconds);
  var ev = app.nextEventMatchingMaskUntilDateInModeDequeue(0xffffffff, until, RUNLOOP_MODE, true);
  if (ev && !ev.isNil()) app.sendEvent(ev);
}

var MOD_CONTROL = 1 << 18;
var MOD_OPTION = 1 << 19;
var MOD_COMMAND = 1 << 20;

/** Run the chosen menu action. Returns true when Raycast should send ⌘V. */
function perform(action, mods) {
  if (!action) return false;
  if (action.type === "history") {
    if (mods & MOD_OPTION && !(mods & MOD_CONTROL)) {
      deleteHistory(action.id); // ⌥: delete
      return false;
    }
    var e = findHistory(action.id);
    if (!e) return false;
    writeEntryToPasteboard(e, (mods & MOD_COMMAND) !== 0); // ⌘: paste as plain text
    if (mods & MOD_CONTROL) {
      selfMarker.id = "__skip__"; // ⌃: paste and delete (do not re-record)
      deleteHistory(action.id);
    }
    return true;
  }
  if (action.type === "snippet") {
    var folders = readJSON(p("snippets.json"), []) || [];
    for (var i = 0; i < folders.length; i++) {
      if (folders[i].id !== action.folderId) continue;
      for (var j = 0; j < folders[i].snippets.length; j++) {
        var s = folders[i].snippets[j];
        if (s.id === action.snippetId) {
          writeEntryToPasteboard({ kind: "text", text: s.content }, true);
          return true;
        }
      }
    }
    return false;
  }
  if (action.type === "clear") {
    if (cfg.confirmClear) {
      var a = $.NSAlert.alloc.init;
      a.messageText = $("Clear clipboard history?");
      a.informativeText = $("This cannot be undone.");
      a.addButtonWithTitle($("Clear"));
      a.addButtonWithTitle($("Cancel"));
      app.activateIgnoringOtherApps(true);
      if (a.runModal !== 1000) return false;
    }
    clearHistory();
    return false;
  }
  if (action.type === "open") {
    ws.openURL($.NSURL.URLWithString($(cfg.deeplinkBase + action.path)));
    return false;
  }
  return false;
}

function respond(id, action) {
  writeJSON(p("response.json"), { id: id, action: action, at: Date.now() });
}

function handleRequest() {
  var req = readJSON(p("request.json"), null);
  removeFile(p("request.json"));
  if (!req) return;
  loadConfig();

  if (req.cmd === "ping") {
    respond(req.id, "pong");
    return;
  }

  if (req.cmd === "paste") {
    // From the Raycast list or menu bar: just write the item back with all of its types
    var e = findHistory(req.historyId);
    if (e) writeEntryToPasteboard(e, !!req.plain);
    respond(req.id, e ? "paste" : "none");
    return;
  }

  if (req.cmd === "popup") {
    var prev = frontApp().ref;
    var menu = buildMenu(req.menu || "main", req.folder);
    picked = null;
    app.activateIgnoringOtherApps(true);
    pump(0.01);
    menu.popUpMenuPositioningItemAtLocationInView($(), $.NSEvent.mouseLocation, $());
    for (var i = 0; i < 20 && !picked; i++) pump(0.005);
    var action = picked ? menuTable[picked.tag] : null;
    var shouldPaste = false;
    try {
      shouldPaste = perform(action, picked ? picked.mods : 0);
    } catch (err) {
      log("perform failed: " + err);
    }
    if (prev && !prev.isNil()) prev.activateWithOptions(2 /* NSApplicationActivateIgnoringOtherApps */);
    if (shouldPaste) for (var k = 0; k < 6; k++) pump(0.01); // let the previous app become active
    respond(req.id, shouldPaste ? "paste" : "none");
  }
}

