import { Action, ActionPanel, Color, Icon, List, useNavigation, Keyboard } from "@raycast/api";
import type { AppSummary } from "../lib/argocd/types";
import type { ArgoInstance } from "../lib/config/instances";
import { appKey } from "../lib/search/score";
import { ApplicationDetail } from "./ApplicationDetail";
import { environmentColor, healthIcon, syncIcon } from "./statusVisuals";
import { makeClient } from "./deps";

interface Props {
  app: AppSummary;
  instance: ArgoInstance;
  showInstance: boolean;
  onRefresh: (instanceId?: string) => void;
}

export function ApplicationListItem({ app, instance, showInstance, onRefresh }: Props) {
  const { push } = useNavigation();
  const url = makeClient(instance).appUrl(app.name, app.namespace);

  const accessories: List.Item.Accessory[] = [
    { icon: syncIcon(app.sync), tooltip: `Sync: ${app.sync}` },
    { icon: healthIcon(app.health), tooltip: `Health: ${app.health}` },
  ];
  if (app.appSetName) {
    accessories.push({ icon: Icon.Layers, tooltip: `Generated by ${app.appSetName}` });
  }
  if (showInstance) {
    accessories.push({ tag: { value: instance.name, color: environmentColor(instance.env) } });
  }

  return (
    <List.Item
      id={appKey(app)}
      icon={{ source: Icon.Box, tintColor: Color.SecondaryText }}
      title={app.name}
      subtitle={app.project}
      accessories={accessories}
      actions={
        <ActionPanel>
          <ActionPanel.Section>
            <Action
              title="Show Details"
              icon={Icon.Sidebar}
              onAction={() => push(<ApplicationDetail app={app} instance={instance} onRefresh={onRefresh} />)}
            />
            <Action.OpenInBrowser title="Open in ArgoCD" url={url} />
          </ActionPanel.Section>
          <ActionPanel.Section>
            <Action.CopyToClipboard title="Copy Application Name" content={app.name} />
            <Action.CopyToClipboard title="Copy ArgoCD URL" content={url} shortcut={Keyboard.Shortcut.Common.Copy} />
            {app.repoUrl ? <Action.OpenInBrowser title="Open Source Repository" url={app.repoUrl} /> : null}
          </ActionPanel.Section>
          <ActionPanel.Section>
            <Action
              title={`Refresh ${instance.name}`}
              icon={Icon.ArrowClockwise}
              shortcut={Keyboard.Shortcut.Common.Refresh}
              onAction={() => onRefresh(instance.id)}
            />
            <Action
              title="Refresh All Instances"
              icon={Icon.ArrowClockwise}
              shortcut={{ modifiers: ["cmd", "shift"], key: "r" }}
              onAction={() => onRefresh()}
            />
          </ActionPanel.Section>
        </ActionPanel>
      }
    />
  );
}
