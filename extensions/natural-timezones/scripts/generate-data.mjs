import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const root = path.resolve(import.meta.dirname, "..", process.env.TIME_APP_ROOT || "../time");
const out = path.resolve(import.meta.dirname, "../src/generated/timezone-data.ts");
const context = { window: {} };
vm.createContext(context);

for (const file of ["data.js", "toponyms.js"]) {
  const source = path.join(root, file);
  if (!fs.existsSync(source)) {
    throw new Error(`Missing ${source}. Set TIME_APP_ROOT to the Time web app checkout.`);
  }
  vm.runInContext(fs.readFileSync(source, "utf8"), context, { filename: file });
}

const source = `/* Generated by scripts/generate-data.mjs from ../../data.js and ../../toponyms.js. */
export const TIMEZONE_DATA = ${JSON.stringify(context.window.TIMEZONE_DATA)};
export const TIMEZONE_TOPONYMS = ${JSON.stringify(context.window.TIMEZONE_TOPONYMS ?? [])};
`;

fs.writeFileSync(out, source);
