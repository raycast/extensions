export type StringKey = keyof typeof TEXT;

export type Translate = (key: StringKey, values?: Record<string, string | number>) => string;

/** The text for `key`, with `{name}` placeholders filled from `values`. */
export const t: Translate = (key, values) => {
  const template: string = TEXT[key] ?? key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
};

