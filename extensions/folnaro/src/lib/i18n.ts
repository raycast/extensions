export const STRINGS: Record<Language, Record<StringKey, string>> = { en, de };

/** "Automatic" follows the first preferred macOS language: German if it starts with "de". */
export function resolveLanguage(preference: string | undefined, preferredLanguages: string[]): Language {
  if (preference === "de" || preference === "en") return preference;
  const first = preferredLanguages.find((language) => language.trim().length > 0) ?? "en";
  return first.toLowerCase().startsWith("de") ? "de" : "en";
}

/** Parses `defaults read -g AppleLanguages`, a property list array like `( "de-DE", en )`. */
export function parseAppleLanguages(output: string): string[] {
  return Array.from(output.matchAll(/"?([A-Za-z]{2,3}(?:[-_][A-Za-z0-9]+)*)"?\s*,?/g))
    .map((match) => match[1])
    .filter((value) => value.length >= 2);
}

export type Translate = (key: StringKey, values?: Record<string, string | number>) => string;

export function translator(language: Language): Translate {
  const table = STRINGS[language];
  return (key, values) => {
    const template = table[key] ?? en[key] ?? key;
    if (!values) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
  };
}

export function locale(language: Language): string {
  return language === "de" ? "de-DE" : "en-US";
}
