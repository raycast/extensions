export class HelperMissingError extends Error {
  constructor(site: Site, minVersion?: string) {
    super(
      minVersion
        ? `Install or update the Bricks Raycast Helper plugin on ${site.name} (version ${minVersion} or later). Bricks Site Health has it ready to upload (⌘⇧H).`
        : `Install the Bricks Raycast Helper plugin on ${site.name} (and add an application password). Bricks Site Health has it ready to upload (⌘⇧H).`,
    );
  }
}

/**
 * Calls a helper plugin endpoint. `minVersion` is the plugin version that added the endpoint,
 * so the error can say which version is needed.
 */
export async function helperRequest<T>(
  site: Site,
  route: string,
  params: Record<string, string> = {},
  options: RequestOptions & { minVersion?: string } = {},
): Promise<T> {
  if (!site.username || !site.appPassword) throw new HelperMissingError(site);
  try {
    return await wpRequest<T>(site, `/${HELPER_NAMESPACE}${route}`, params, options);
  } catch (error) {
    if (isMissingRoute(error)) throw new HelperMissingError(site, options.minVersion);
    if (error instanceof WordPressError && error.code === PRO_REQUIRED_CODE)
      throw new ProLicenseError(site, error.message);
    throw error;
  }
}

/** Whole-site scans (every element on every page) can take a while on big sites. */
export const SCAN_TIMEOUT = 60000;

export const getDesign = (site: Site) => helperRequest<Design>(site, "/design", {}, { timeout: SCAN_TIMEOUT });
export const getClassDetail = (site: Site, id: string) =>
  helperRequest<ClassDetail>(site, `/class/${id}`, {}, { timeout: SCAN_TIMEOUT });
// Condition texts include post titles, which WordPress returns with HTML entities (&#8211;).
export const getSiteInfo = (site: Site) =>
  helperRequest<SiteInfo>(site, "/site").then((info) => ({
    ...info,
    theme_styles: info.theme_styles.map((style) => ({ ...style, conditions: style.conditions.map(decodeEntities) })),
  }));

export interface SettingKey {
  /** e.g. "padding" */
  property: string;
  breakpoint?: string;
  state?: string;
}

/** Splits Bricks setting keys like "_padding:tablet_portrait:hover" into property, breakpoint and state. */
export function parseSettingKey(key: string, breakpointKeys: Set<string>): SettingKey {
  const [base, ...rest] = key.replace(/:variant-[^:]+/, "").split(":");
  const property = base.replace(/^_/, "");
  if (rest.length === 0) return { property };
  if (breakpointKeys.has(rest[0])) {
    return { property, breakpoint: rest[0], state: rest.length > 1 ? `:${rest.slice(1).join(":")}` : undefined };
  }
  return { property, state: `:${rest.join(":")}` };
}

/** "gridTemplateColumns" → "grid template columns", "cssCustom" → "custom CSS". */
export function propertyLabel(property: string): string {
  if (property === "cssCustom") return "custom CSS";
  return property.replace(/([A-Z])/g, " $1").toLowerCase();
}

const UTILITY_PROPERTIES: Record<string, string> = {
  bg: "background-color",
  text: "color",
  border: "border-color",
  outline: "outline-color",
  fill: "fill",
  stroke: "stroke",
};

/** The utility classes Bricks generates for a color, e.g. ".bg-primary { background-color: var(--primary) }". */
export function colorUtilityClasses(color: PaletteColor): { className: string; css: string }[] {
  const variable = color.raw?.match(/^var\(--([^)]+)\)$/)?.[1];
  if (!variable) return [];
  return (color.utility_classes ?? [])
    .filter((prefix) => UTILITY_PROPERTIES[prefix])
    .map((prefix) => ({
      className: `${prefix}-${variable}`,
      css: `.${prefix}-${variable} { ${UTILITY_PROPERTIES[prefix]}: ${color.raw}; }`,
    }));
}

/**
 * Resolves var(--x) references in a value using the site's variables and colors, so
 * "var(--space-m)" shows what it really is. Stops after a few levels to avoid cycles.
 */
export function resolveValue(value: string, lookup: Map<string, string>, depth = 0): string {
  if (depth > 5) return value;
  const resolved = value.replace(/var\(--([\w-]+)(?:,\s*([^)]*))?\)/g, (match, name: string, fallback?: string) => {
    const found = lookup.get(name);
    if (found !== undefined) return resolveValue(found, lookup, depth + 1);
    return fallback ?? match;
  });
  return resolved;
}

/** name (without --) → value, for variables and palette colors that define a variable. */
export function buildLookup(design: Design): Map<string, string> {
  const lookup = new Map<string, string>();
  for (const variable of design.variables) lookup.set(variable.name, variable.value);
  for (const palette of design.palettes) {
    for (const color of palette.colors) {
      const name = color.raw?.match(/^var\(--([^)]+)\)$/)?.[1];
      if (name && color.light && !color.light.startsWith("var(")) lookup.set(name, color.light);
    }
  }
  return lookup;
}

/** CSS reference for a color: its variable when it has one (var(--primary)), else its value. */
export function colorReference(color: PaletteColor): string {
  return color.raw || color.light || "";
}

/** A concrete CSS color Raycast can draw as a swatch, if the color has one. */
export function swatchColor(color: PaletteColor): string | undefined {
  const value = color.light ?? (color.raw && !color.raw.startsWith("var(") ? color.raw : null);
  if (!value || value.startsWith("var(")) return undefined;
  return value;
}
