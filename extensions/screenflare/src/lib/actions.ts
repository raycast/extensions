export type ScreenflareAction = (typeof actions)[number];
export type ActionID = ScreenflareAction["id"];

export function getAction(id: ActionID): ScreenflareAction {
  const action = actions.find((item) => item.id === id);
  if (!action) throw new Error(`Unknown Screenflare action: ${id}`);
  return action;
}
