/**
 * Bundles the background worker into `assets/worker.mjs`.
 *
 * `ray build` only compiles the entry points declared as commands in package.json, and
 * the worker is deliberately not one — it must run with no Raycast around it. Bundling
 * it here keeps a single source of truth for the synthesis code and leaves the worker
 * with no dependency on `node_modules` at run time.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/worker.ts"],
  outfile: "assets/worker.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  minify: false,
  sourcemap: false,
  // Nothing is external: `assets/` has no node_modules next to it, so anything left
  // unbundled would only fail at the moment the user presses Shift + >.
  banner: {
    js:
      "// Generated by esbuild.mjs from src/worker.ts. Do not edit by hand.\n" +
      "import { createRequire as __createRequire } from 'node:module';\n" +
      "const require = __createRequire(import.meta.url);",
  },
  logLevel: "info",
});
