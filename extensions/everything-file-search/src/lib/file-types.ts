export function fileTypeById(id: string): FileType {
  return FILE_TYPES.find((t) => t.id === id) ?? FILE_TYPES[0];
}

/** Pick a row icon by file extension */
export function iconForFile(
  name: string,
  type: "file" | "folder",
  typeDefs: FileType[] = FILE_TYPES,
): string {
  if (type === "folder") return Icon.Folder;
  const dot = name.lastIndexOf(".");
  const ext = dot >= 0 ? name.slice(dot + 1).toLowerCase() : "";
  for (const t of typeDefs) {
    if (t.extensions && t.extensions.includes(ext)) return t.icon;
  }
  return Icon.Document;
}

