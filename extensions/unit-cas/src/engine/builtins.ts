export function canonicalFunc(name: string): string | undefined {
  if (name === "Σ") return "sum";
  if (name === "Π") return "product";
  const k = name.toLowerCase().replace(/^Δ/i, "δ");
  if (k in FUNCS) return k;
  if (k in ALIASES) return ALIASES[k] === "cbrt" ? "cbrt" : ALIASES[k];
  // "sin⁻¹" style inverse names
  const inv = /^(sin|cos|tan|sinh|cosh|tanh)⁻¹$/.exec(k);
  if (inv) return "arc" + inv[1];
  return undefined;
}

