/// Names in code: a query that's a name finds it exactly, and the place that defines it rather than every place
/// that uses it; a result opens at the line that matched.
public enum CodeLookup {
    /// The words keyword search keeps a name from code as ("quantize_row_q8_0_ref" → quantize row q8 0 ref, as one
    /// phrase), when the query is one: snake_case, camelCase, dotted, or with digits. Nil for words anyone would say
    /// ("retry", "Renamer"), which are searched as words and by meaning.
    public static func identifier(_ query: String) -> [String]? {
        var name = query.trimmingCharacters(in: .whitespacesAndNewlines)
        if name.hasSuffix("()") { name.removeLast(2) }
        guard name.range(of: #"^[A-Za-z_$][A-Za-z0-9_$]*(?:(?:\.|::|->|#)[A-Za-z_$][A-Za-z0-9_$]*)*$"#,
                         options: .regularExpression) != nil else { return nil }
        let camel = name.dropFirst().contains(where: \.isUppercase) && name.contains(where: \.isLowercase)
        guard camel || name.contains(where: { "_.:#$".contains($0) || $0.isNumber }) else { return nil }
        return name.lowercased().components(separatedBy: CharacterSet.alphanumerics.inverted).filter { !$0.isEmpty }
    }

    /// The keyword search pattern for an identifier's words: one phrase, so they match only side by side, as written.
    static func phrase(_ words: [String]) -> String {
        "\"" + words.joined(separator: " ") + "\""
    }

    /// Where `name` is defined in `text` (a stretch whose first line is `first`): the line, and how surely. 2 after a
    /// word that defines something (def, func, class, function, struct, #define, @implementation…) or as a C-style
    /// definition (a type before it, its parameters after it, no "=" or call around it); 1 for a declaration (the
    /// same, ending in ";"). Nil when the stretch only uses it.
    static func definition(of name: String, in text: String, first: Int) -> (line: Int, strength: Int)? {
        var best: (line: Int, strength: Int)?
        for (offset, line) in lines(text).enumerated() {
            for range in occurrences(of: name, in: line) {
                let before = line[..<range.lowerBound].trimmingCharacters(in: .whitespaces)
                let after = line[range.upperBound...].trimmingCharacters(in: .whitespaces)
                let strength = definitionStrength(before: before, after: after, line: String(line))
                if strength > (best?.strength ?? 0) { best = (first + offset, strength) }
                if strength == 2 { return best }
            }
        }
        return best
    }

    /// A word that starts a definition ("def", "func", "class", "@implementation"…).
    static func definesSomething(_ word: String) -> Bool { definers.contains(word) && word != "let" && word != "var"
        && word != "const" && word != "val" }

    private static let definers: Set<String> = [
        "def", "func", "fn", "fun", "function", "class", "struct", "enum", "protocol", "interface", "trait", "type",
        "typealias", "actor", "extension", "impl", "module", "namespace", "object", "record", "macro", "const", "let",
        "var", "val", "union", "mod", "sub", "@interface", "@implementation", "@protocol", "#define", "function*",
    ]
    /// Words before a name that mean it's being used, not defined ("await name(…)", "return name(…)").
    private static let users: Set<String> = [
        "return", "await", "yield", "throw", "new", "else", "case", "print", "echo", "assert", "not", "and", "or", "in",
        "is", "do", "go", "defer", "try", "catch", "if", "while", "for", "typeof", "delete", "raise", "import", "from",
    ]

    private static func definitionStrength(before: String, after: String, line: String) -> Int {
        let previous = before.split(whereSeparator: \.isWhitespace).last.map(String.init) ?? ""
        if definers.contains(previous) { return 2 }
        if before.hasPrefix("func ("), before.hasSuffix(")") { return 2 }                     // a Go method
        if before.hasPrefix("- (") || before.hasPrefix("+ (") { return after.hasPrefix(":") || after.isEmpty
            || after.hasPrefix("{") || after.hasPrefix(";") ? 2 : 0 }                          // an Objective-C method
        // C-style: "static void name(…) {", "struct gguf_context * name(…)", not a call or an assignment.
        guard after.hasPrefix("("), !before.isEmpty, !users.contains(previous),
              !before.contains(where: { "=(,.!?".contains($0) }), !before.contains("->"),
              let last = before.last, last.isLetter || last.isNumber || "*&>_]".contains(last) else { return 0 }
        return line.trimmingCharacters(in: .whitespaces).hasSuffix(";") ? 1 : 2
    }

    /// The line (from `first`) to open at for `words`: the first line with one of them that defines something ("def
    /// retry_with_backoff"), else the first such line of code (not a comment), else the first such line. A word counts
    /// as itself or as a part of a name (the "retry" of retryWithBackoff and retry_with_backoff). Nil when none is there.
    static func firstLine(with words: [String], in text: String, first: Int) -> Int? {
        let words = words.filter { $0.count >= 2 }.map { $0.lowercased() }
        guard !words.isEmpty else { return nil }
        var firstCode: Int?, firstAny: Int?
        for (offset, line) in lines(text).enumerated() where words.contains(where: { has($0, line) }) {
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if trimmed.split(whereSeparator: \.isWhitespace).prefix(4).contains(where: { definesSomething(String($0)) }) {
                return first + offset
            }
            if firstCode == nil, !commentStarts.contains(where: trimmed.hasPrefix) { firstCode = offset }
            if firstAny == nil { firstAny = offset }
        }
        return (firstCode ?? firstAny).map { first + $0 }
    }

    /// How comments and docstrings start.
    private static let commentStarts = ["//", "#", "/*", "*", "--", "\"\"\"", "'''", "<!--", ";"]

    /// Whether `line` has `word` (lowercased) as a word or as the start of a name's part.
    private static func has(_ word: String, _ line: Substring) -> Bool {
        let lower = line.lowercased()
        var searchStart = lower.startIndex
        while let found = lower.range(of: word, range: searchStart..<lower.endIndex) {
            // A word or a name's part starts here: at the line's start, after something that isn't a letter or a
            // digit, or at a capital letter (camelCase).
            let start = line.index(line.startIndex, offsetBy: lower.distance(from: lower.startIndex, to: found.lowerBound),
                                   limitedBy: line.endIndex) ?? line.endIndex
            if found.lowerBound == lower.startIndex
                || !lower[lower.index(before: found.lowerBound)].isLetter
                    && !lower[lower.index(before: found.lowerBound)].isNumber
                || start < line.endIndex && line[start].isUppercase {
                return true
            }
            searchStart = found.upperBound
        }
        return false
    }

    private static func lines(_ text: String) -> [Substring] {
        text.split(omittingEmptySubsequences: false, whereSeparator: { $0 == "\n" || $0 == "\r\n" })
    }

    /// Where `name` is in `line` as a whole name (not a part of a longer one), whatever its case.
    private static func occurrences(of name: String, in line: Substring) -> [Range<Substring.Index>] {
        var found: [Range<Substring.Index>] = []
        var start = line.startIndex
        while let range = line.range(of: name, options: .caseInsensitive, range: start..<line.endIndex) {
            let clearBefore = range.lowerBound == line.startIndex || !isNameCharacter(line[line.index(before: range.lowerBound)])
            let clearAfter = range.upperBound == line.endIndex || !isNameCharacter(line[range.upperBound])
            if clearBefore, clearAfter { found.append(range) }
            start = range.upperBound
        }
        return found
    }

    private static func isNameCharacter(_ character: Character) -> Bool {
        character.isLetter || character.isNumber || character == "_" || character == "$"
    }
}
