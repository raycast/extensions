/**
 * 历史记录的时间戳给人看的写法。
 * 文件名里的时间是 `2026-09-12-034033`(快照、配置历史)或 `20260912-034033`(rc 备份),
 * 时分秒挤在一起要自己数位;界面上统一显示成 `2026-09-12 03:40:33`
 */
export function prettyTimestamp(raw: string): string {
  const m = /^(\d{4})-?(\d{2})-?(\d{2})-(\d{2})(\d{2})(\d{2})$/.exec(raw);
  if (!m) return raw;
  return `${m[1]}-${m[2]}-${m[3]} ${m[4]}:${m[5]}:${m[6]}`;
}
