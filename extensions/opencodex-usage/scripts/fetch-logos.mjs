#!/usr/bin/env node
/**
 * Downloads provider logos from svgl.app into assets/logos and regenerates
 * src/provider-logos.ts. Logos are bundled rather than fetched at runtime so the
 * extension stays fast and works offline.
 *
 * Usage: npm run fetch-logos
 */
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const logoDir = join(root, "assets", "logos");

/**
 * Maps opencodex provider ids (see GET /api/provider-presets) to svgl logo titles.
 * Several opencodex providers share one vendor logo (e.g. every Kimi flavour).
 */
const PROVIDER_TO_SVGL = {
  anthropic: "Claude AI",
  "anthropic-apikey": "Claude AI",
  openai: "Codex",
  "openai-apikey": "OpenAI",
  "azure-openai": "Microsoft Azure",
  cursor: "Cursor",
  xai: "Grok",
  grok: "Grok",
  kimi: "Kimi",
  "kimi-code": "Kimi",
  moonshot: "Kimi",
  firepass: "Kimi",
  google: "Gemini",
  "google-vertex": "Gemini",
  gemini: "Gemini",
  openrouter: "OpenRouter",
  groq: "Groq",
  ollama: "Ollama",
  "ollama-cloud": "Ollama",
  deepseek: "DeepSeek",
  cerebras: "Cerebras",
  together: "Together AI",
  huggingface: "Hugging Face",
  nvidia: "NVIDIA",
  mistral: "Mistral AI",
  "qwen-cloud": "Qwen",
  alibaba: "Qwen",
  "alibaba-token-plan": "Qwen",
  "vercel-ai-gateway": "Vercel",
  "cloudflare-ai-gateway": "Cloudflare",
  "gitlab-duo": "GitLab",
  "opencode-go": "OpenCode",
  "opencode-zen": "OpenCode",
  "opencode-free": "OpenCode",
  kilo: "Kilo Code",
  perplexity: "Perplexity AI",
  replit: "Replit",
  windsurf: "Windsurf",
  copilot: "Microsoft Copilot",
};

function slug(provider) {
  return provider.replace(/[^a-z0-9]+/gi, "-").toLowerCase();
}

async function main() {
  const response = await fetch("https://api.svgl.app");
  if (!response.ok) throw new Error(`svgl index failed: ${response.status}`);
  const index = await response.json();

  const byTitle = new Map();
  for (const entry of index) byTitle.set(entry.title.toLowerCase(), entry);

  await rm(logoDir, { recursive: true, force: true });
  await mkdir(logoDir, { recursive: true });

  const mapping = {};
  const missing = [];

  for (const [provider, title] of Object.entries(PROVIDER_TO_SVGL)) {
    const entry = byTitle.get(title.toLowerCase());
    if (!entry) {
      missing.push(`${provider} (no svgl entry for "${title}")`);
      continue;
    }

    // `route` is either a single URL or a { light, dark } pair for monochrome marks.
    const routes =
      typeof entry.route === "string" ? { light: entry.route, dark: entry.route } : entry.route;
    const files = {};
    for (const theme of ["light", "dark"]) {
      const url = routes[theme];
      if (!url) continue;
      const svg = await fetch(url);
      if (!svg.ok) {
        missing.push(`${provider} ${theme} (${svg.status})`);
        continue;
      }
      const name = `${slug(provider)}-${theme}.svg`;
      await writeFile(join(logoDir, name), await svg.text(), "utf8");
      files[theme] = `logos/${name}`;
    }

    if (files.light && files.dark) {
      mapping[provider] =
        files.light === files.dark ? files.light : { light: files.light, dark: files.dark };
    }
  }

  const generated = `// Generated by scripts/fetch-logos.mjs — do not edit by hand.
// Logos courtesy of https://svgl.app

export type LogoSource = string | { light: string; dark: string };

export const PROVIDER_LOGO_FILES: Record<string, LogoSource> = ${JSON.stringify(mapping, null, 2)};
`;
  await writeFile(join(root, "src", "provider-logos.ts"), generated, "utf8");

  const written = (await readdir(logoDir)).length;
  console.log(`Wrote ${written} svg files for ${Object.keys(mapping).length} providers.`);
  if (missing.length) console.warn(`Missing: ${missing.join(", ")}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
