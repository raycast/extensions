let table: Uint16Array | undefined;

function indexes(): Uint16Array {
  if (table) return table;
  const bytes = inflateSync(Buffer.from(PACKED, "base64"));
  const values = new Uint16Array(bytes.length / 2);
  for (let i = 0; i < values.length; i++) {
    values[i] = bytes[i * 2]! | (bytes[i * 2 + 1]! << 8);
  }
  table = values;
  return values;
}

function syllableOf(char: string): string | undefined {
  const code = char.charCodeAt(0);
  if (code < START || code > 0x9fa5) return undefined;
  const id = indexes()[code - START];
  return id ? SYLLABLES[id - 1] : undefined;
}

/** Full pinyin and initials of the Chinese characters in text. */
export function pinyinKeys(text: string): { full: string; initials: string } {
  let full = "";
  let initials = "";
  for (const char of text) {
    const syllable = syllableOf(char);
    if (!syllable) continue;
    full += syllable;
    initials += syllable[0];
  }
  return { full, initials };
}
