import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const [root, output] = process.argv.slice(2);
const result = await build({
  entryPoints: [join(root, "editor/editor.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "safari16",
  minify: true,
  legalComments: "eof",
  write: false,
});
const files = {
  "editor.js": result.outputFiles[0].contents,
  "editor.css": await readFile(join(root, "editor/editor.css")),
  "index.html": await readFile(join(root, "editor/index.html")),
};
let swift =
  "// Generated by the Swift Package build plugin. Do not commit.\nimport Foundation\nenum EmbeddedEditor {\n";
swift += "    static func write(to directory: URL) throws {\n";
for (const [name, bytes] of Object.entries(files)) {
  const chunks = Buffer.from(bytes)
    .toString("base64")
    .match(/.{1,16000}/g);
  swift += `        let ${name.split(".")[1]} = [${chunks.map((chunk) => JSON.stringify(chunk)).join(",\n")}].joined()\n`;
  swift += `        try Data(base64Encoded: ${name.split(".")[1]})!.write(to: directory.appendingPathComponent(${JSON.stringify(name)}))\n`;
}
swift += "    }\n}\n";
await writeFile(output, swift);
