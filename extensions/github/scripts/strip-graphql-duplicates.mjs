#!/usr/bin/env node
/**
 * @graphql-codegen/typescript-operations currently re-emits used input types and
 * enums after the schema plugin output, which collides with `export enum`s.
 * Strip that duplicate block so the file typechecks.
 */
import { readFileSync, writeFileSync } from "node:fs";

const path = "src/generated/graphql.ts";
const text = readFileSync(path, "utf8");
const marker = "/** Autogenerated input type of CreateLinkedBranch */";
const first = text.indexOf(marker);
const second = text.indexOf(marker, first + 1);
const end = text.indexOf("export type CreateLinkedBranchMutationVariables", second);

if (first === -1 || second === -1 || end === -1 || !(second > first && end > second)) {
  console.log("strip-graphql-duplicates: nothing to strip");
  process.exit(0);
}

writeFileSync(path, text.slice(0, second) + text.slice(end));
console.log("strip-graphql-duplicates: removed duplicate type block");
